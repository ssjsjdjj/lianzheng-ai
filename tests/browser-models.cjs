/* Contract/UI test against tests/mock_provider.py. This is NOT a live LLM acceptance test. */
const {chromium}=require('playwright');
const fs=require('fs');
const path=require('path');
(async()=>{
 fs.mkdirSync('test-results',{recursive:true});
 const browser=await chromium.launch({...(process.platform==='win32'?{channel:'msedge'}:{}),headless:true});
 const page=await browser.newPage({viewport:{width:1512,height:1100}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const base=process.env.LZ_TEST_URL||'http://127.0.0.1:8766';
 await page.goto(base,{waitUntil:'networkidle'});
 await page.locator('#open-model-settings').click();
 await page.locator('#provider-select').selectOption('compatible');
 await page.locator('#provider-base').fill('http://127.0.0.1:8770');
 await page.locator('#provider-model').fill('contract-test-stub');
 await page.locator('#provider-key').fill('browser-test-placeholder-key');
 await page.locator('#provider-remember').uncheck();
 await page.locator('#connect-model').click();
 await page.waitForFunction(()=>document.querySelector('#model-connection-result').textContent.includes('验证成功'));
 if(await page.locator('#provider-key').inputValue())throw Error('Credential remained in field after saving');
 const settings=await (await page.request.get(base+'/api/model/settings')).text();
 if(settings.includes('browser-test-placeholder-key'))throw Error('Credential echoed in configuration response');
 await page.locator('#close-model').click();
 if(!await page.locator('#use-model').isChecked())throw Error('Verified model was not enabled');
 await page.locator('#open-demo').click();
  await page.locator('.demo-hub-legacy > summary').filter({hasText:'构造样例与历史模型验收'}).click();
  await page.locator('#prepare-demo').click();
 await page.waitForFunction(()=>!document.querySelector('[data-demo-step="2"]').disabled);
 await page.locator('[data-demo-step="2"]').click();
 await page.waitForFunction(()=>document.querySelector('#answer .model-claim'));
 if(!(await page.locator('#answer').innerText()).includes('contract-test-stub'))throw Error('Returned model metadata missing');
 await page.locator('[data-demo-step="3"]').click();
 await page.waitForFunction(()=>document.querySelector('#conversation-context').textContent.includes('2 轮'));
 await page.locator('#question').fill('这些检查还需要注意什么？');await page.locator('#ask-button').click();
 await page.waitForFunction(()=>document.querySelector('#conversation-context').textContent.includes('3 轮'));
 const history=await (await page.request.get(base+'/api/snapshots/demo-before/history')).json();
 if(history[0].answer.facts.target_version!=='4.18.1'||!history[0].answer.parent_id)throw Error('Followup target context was not preserved');
 await page.screenshot({path:path.resolve('test-results/model-contract-ui.png'),fullPage:false});
 await page.locator('[data-demo-step="4"]').click();
 await page.waitForFunction(()=>document.querySelector('.compare-result.remaining')?.textContent.includes('GHSA-29mw-wpgm-hmr9'));
 await page.locator('[data-demo-step="5"]').click();
 await page.waitForFunction(()=>document.querySelector('.compare-result.resolved')?.textContent.includes('GHSA-29mw-wpgm-hmr9'));
 const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#download-demo').click()]);
 const report=path.resolve('test-results/contract-demo-report.html');await download.saveAs(report);
 const text=fs.readFileSync(report,'utf8');
 if(text.includes('browser-test-placeholder-key')||!text.includes('contract-test-stub'))throw Error('Report secret handling or model attribution failed');
 await page.locator('[data-view="questions"]').click();
 await page.locator('#question').fill('__BAD_QUOTE__ 这条建议的依据？');await page.locator('#ask-button').click();
 await page.waitForFunction(()=>!document.querySelector('#ask-button').disabled);
 if(await page.locator('.model-claim').count())throw Error('Unverified quotation was displayed as an accepted claim');
 if(!(await page.locator('#answer').innerText()).includes('回退本地'))throw Error('Rejected model response did not show fallback status');
 await page.setViewportSize({width:390,height:844});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1))throw Error('Mobile model UI overflows');
 await page.locator('#open-model-settings').click();await page.locator('#provider-model').fill('reject-test-model');await page.locator('#connect-model').click();
 await page.waitForFunction(()=>document.querySelector('#model-connection-result').textContent.includes('鉴权失败'));
 const after=await (await page.request.get(base+'/api/model/settings')).json();
 if(after.model!=='contract-test-stub')throw Error('Failed configuration test overwrote working configuration');
 await page.locator('#close-model').click();
 if(errors.length)throw Error(errors.join('\n'));
 console.log(JSON.stringify({kind:'simulated-provider-ui-contract',checks:['model setup','minimal API probe','secret cleared','configuration redaction','model enabled','quoted claims','usage metadata','multi-turn context','partial and full comparison','HTML report','rejected quote fallback','mobile model UI','failed configuration preserves old settings'],pageErrors:errors}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
