const {chromium}=require('playwright');
const fs=require('fs');
const path=require('path');
fs.mkdirSync('test-results',{recursive:true});
(async()=>{
 const browser=await chromium.launch({...(process.platform==='win32'?{channel:'msedge'}:{}),headless:true});
 const page=await browser.newPage({viewport:{width:1512,height:1100},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const base=process.env.LZ_TEST_URL||'http://127.0.0.1:8765';
 await page.goto(base,{waitUntil:'networkidle'});
 await page.locator('.risk-item').first().waitFor();
 if(await page.locator('.risk-item').count()!==5)throw Error('Expected five frozen OSV advisories');
 if(await page.locator('.graph-node').count()!==5)throw Error('Expected five occurrence nodes');
 await page.locator('[data-prompt]').first().click();
 await page.locator('#answer h3').waitFor();
 if(!(await page.locator('#answer').innerText()).includes('2 个组件出现位置'))throw Error('Graph answer did not report two occurrences');
 if(await page.locator('.citation-link').count()!==2)throw Error('Expected two cited occurrence records');
 await page.locator('.graph-node[data-node="lodash-report"]').click();
 if(!(await page.locator('#node-detail').innerText()).includes('4.17.20'))throw Error('Node inspector failed');
 await page.locator('#evidence-list details').first().locator('summary').click();
 await page.locator('body').click({position:{x:500,y:100}});
 await page.screenshot({path:path.resolve('test-results/overview.png'),fullPage:true});
 await page.locator('[data-mode="text"]').click();
 await page.locator('[data-prompt]').first().click();
 await page.waitForFunction(()=>document.querySelector('#answer').textContent.includes('不提供依赖路径判断'));
 await page.locator('[data-view="compare"]').click();
 await page.locator('.compare-result.remaining').waitFor();
 if(!(await page.locator('.compare-result.remaining').innerText()).includes('GHSA-29mw-wpgm-hmr9'))throw Error('Partial remediation incorrectly resolved target');
 await page.locator('#compare-after').selectOption('demo-resolved');
 await page.locator('#compare-form button').click();
 await page.waitForFunction(()=>document.querySelector('.compare-result.resolved')?.textContent.includes('GHSA-29mw-wpgm-hmr9'));
 await page.screenshot({path:path.resolve('test-results/compare.png'),fullPage:true});
 await page.locator('[data-view="overview"]').click();
 await page.locator('#snapshot-select').selectOption('demo-resolved');
 await page.waitForFunction(()=>document.querySelector('#risk-count').textContent==='0');
 await page.setViewportSize({width:390,height:844});
 await page.locator('#snapshot-select').selectOption('demo-before');
 await page.locator('.risk-item').first().waitFor();
 await page.screenshot({path:path.resolve('test-results/mobile.png'),fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
 if(overflow)throw Error('Mobile page overflows horizontally');
 await page.setViewportSize({width:1512,height:1100});
 if(process.env.LZ_TEST_IMPORT==='1'){
   const bom=JSON.parse(fs.readFileSync('fixtures/before.cdx.json','utf8'));
   await page.locator('#open-import').click();
   await page.locator('#import-project').fill('UI 回归样例');
   await page.locator('#import-label').fill('浏览器导入');
   await page.locator('#bom-file').setInputFiles({name:'example.cdx.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(bom))});
   await page.locator('#import-submit').click();
   await page.waitForFunction(()=>!document.querySelector('#import-dialog').open);
   if(!(await page.locator('#sidebar-project').innerText()).includes('UI 回归样例'))throw Error('Uploaded project was not selected');
 }
 if(errors.length)throw Error(errors.join('\n'));
 console.log(JSON.stringify({browser:'Microsoft Edge headless',checks:['risk list','occurrence graph','grounded answer','citations','node inspector','text baseline','partial comparison','full comparison','snapshot switching','mobile overflow',...(process.env.LZ_TEST_IMPORT==='1'?['SBOM file upload']:[])],pageErrors:errors}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
