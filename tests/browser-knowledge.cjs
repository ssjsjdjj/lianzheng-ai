/* Run against an isolated database: this test deliberately imports and removes a demo document. */
const {chromium}=require('playwright');
const fs=require('fs');
const path=require('path');
(async()=>{
  fs.mkdirSync('test-results',{recursive:true});
  const browser=await chromium.launch({...(process.platform==='win32'?{channel:'msedge'}:{}),headless:true});
  const page=await browser.newPage({viewport:{width:1512,height:1100},deviceScaleFactor:1});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const base=process.env.LZ_TEST_URL||'http://127.0.0.1:8766';
  await page.goto(base,{waitUntil:'networkidle'});
  await page.locator('.risk-item').first().waitFor();
  await page.locator('[data-view="documents"]').click();
  await page.locator('#open-document').click();
  await page.locator('#document-binding').selectOption({label:'lodash @ 4.17.20'});
  await page.locator('#document-target').fill('4.18.1');
  await page.locator('#document-title').fill('浏览器验收的迁移说明');
  await page.locator('#document-file').setInputFiles(path.resolve('fixtures/migration-demo.md'));
  await page.locator('#document-submit').click();
  await page.waitForFunction(()=>!document.querySelector('#document-dialog').open);
  await page.waitForFunction(()=>document.querySelector('#document-count').textContent==='1');
  await page.locator('.document-item summary').click();
  await page.waitForFunction(()=>document.querySelector('.document-item pre').textContent.includes('导出快照校验'));
  await page.locator('[data-view="questions"]').click();
  await page.locator('#question').fill('升级到 4.18.1 有哪些迁移检查要求？');
  await page.locator('#ask-button').click();
  await page.waitForFunction(()=>document.querySelector('#answer').textContent.includes('导入文档'));
  if(!(await page.locator('#evidence-list').innerText()).includes('用户导入文档'))throw Error('Document provenance missing');
  if(!(await page.locator('#evidence-list').innerText()).includes('行第'))throw Error('Original line locator missing');
  await page.locator('[data-view="documents"]').click();
  await page.screenshot({path:path.resolve('test-results/knowledge-desktop.png'),fullPage:true});
  if(await page.locator('.history-item').count()<1)throw Error('History was not refreshed');
  await page.reload({waitUntil:'networkidle'});
  await page.locator('.history-item').first().waitFor();
  await page.locator('.history-item').first().click();
  if(!(await page.locator('#answer').innerText()).includes('导入文档'))throw Error('History did not restore original evidence');
  await page.locator('#question').fill('升级到 4.17.21 有哪些迁移检查要求？');
  await page.locator('#ask-button').click();
  await page.waitForFunction(()=>!document.querySelector('#ask-button').disabled);
  if((await page.locator('#evidence-list').innerText()).includes('用户导入文档'))throw Error('Wrong target-version document leaked into answer');
  // Delayed answer must not overwrite a newly selected vulnerability on the same snapshot.
  await page.route('**/api/snapshots/demo-before/ask',async route=>{
    const response=await route.fetch();await new Promise(r=>setTimeout(r,600));await route.fulfill({response});
  });
  await page.locator('#question').fill('这个漏洞通过哪些路径进入项目？');
  await page.locator('#ask-button').click();
  await page.waitForTimeout(80);
  await page.locator('.risk-item').first().click();
  await page.waitForFunction(()=>!document.querySelector('#ask-button').disabled);
  if(await page.locator('#answer h3').count())throw Error('Stale answer overwrote newly selected risk');
  await page.unroute('**/api/snapshots/demo-before/ask');
  await page.locator('[data-view="documents"]').click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.resolve('test-results/knowledge-mobile.png'),fullPage:true});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1))throw Error('Knowledge view overflows on mobile');
  await page.locator('[data-remove-document]').first().click();
  await page.waitForFunction(()=>document.querySelector('#document-count').textContent==='0');
  if(errors.length)throw Error(errors.join('\n'));
  console.log(JSON.stringify({checks:['document file upload','version binding','original line locators','document provenance','history refresh','history after reload','original evidence replay','target version isolation','stale response protection','mobile overflow','document removal'],pageErrors:errors}));
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
